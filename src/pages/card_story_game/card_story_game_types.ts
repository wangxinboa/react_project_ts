// ============================================================
// 卡牌标签定义
// ============================================================
export interface TagItem {
	/** 标签的唯一标识符（正整数）。规则、卡牌模板将来都以 id 引用标签 */
	id: number;
	/** 标签的展示名（可重命名，不参与引用） */
	key: string;
	/** 标签的展示描述 */
	desc: string;
}

// ============================================================
// 全局游戏配置
// ============================================================
export interface GameConfig {
	allTags: TagItem[];
	allRules: Record<string, unknown>;
	cardTemplates: unknown[];
}
